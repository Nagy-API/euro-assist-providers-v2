<?php

namespace App\Services\Legacy;

use App\Models\LegacyMigrationBatch;
use App\Models\LegacyStagingRow;

/**
 * Aggregate-only, sanitized reports for docs/legacy-reports/. They contain counts, state and
 * reason-code distributions and signal-kind counts only: never a name, phone, address, e-mail,
 * URL, id of a source row or batch uuid.
 */
class LegacyReportWriter
{
    public function __construct(private readonly LegacyReconciler $reconciler, private readonly RowNormalizer $normalizer) {}

    /**
     * @param  array<string, mixed>|null  $reconciliation  pass an existing result to avoid recomputing
     * @return array<string, mixed>
     */
    public function build(LegacyMigrationBatch $batch, ?array $reconciliation = null): array
    {
        $rec = $reconciliation ?? $this->reconciler->reconcile($batch);

        return $rec + [
            'snapshot_sha256_prefix' => substr($batch->snapshot_sha256, 0, 8),
            'mapping_version' => $batch->mapping_version,
            'batch_status' => $batch->status,
            'rehearsal' => (bool) $batch->is_rehearsal,
            'coordinates' => $this->coordinateStats($batch),
            'revision_bumps' => array_sum((array) (($batch->counts ?? [])['revision_bumps'] ?? [])),
        ];
    }

    /**
     * Writes docs/legacy-reports/<name>.md and returns the path.
     *
     * @param  array<string, mixed>|null  $reconciliation
     */
    public function write(LegacyMigrationBatch $batch, ?array $reconciliation = null, ?string $name = null): string
    {
        $report = $this->build($batch, $reconciliation);
        $dir = (string) config('legacy.reports_path');
        if (! is_dir($dir) && ! mkdir($dir, 0775, true) && ! is_dir($dir)) {
            throw new LegacyException('The report directory could not be created.');
        }

        $name ??= 'reconciliation-'.$report['snapshot_sha256_prefix'].'-'.$batch->mapping_version.($batch->is_rehearsal ? '-rehearsal' : '');
        $path = rtrim($dir, '/\\').DIRECTORY_SEPARATOR.preg_replace('/[^A-Za-z0-9._-]/', '-', $name).'.md';
        file_put_contents($path, $this->render($report));

        return $path;
    }

    /** @param array<string, mixed> $r */
    public function render(array $r): string
    {
        $out = [];
        $out[] = '# Legacy migration reconciliation (aggregate only)';
        $out[] = '';
        $out[] = 'Generated by `php artisan legacy:report`. Counts only: no provider names, phones, addresses, e-mails, URLs or row identifiers.';
        $out[] = '';
        $out[] = '- Snapshot SHA-256 prefix: `'.$r['snapshot_sha256_prefix'].'`';
        $out[] = '- Mapping version: `'.$r['mapping_version'].'`';
        $out[] = '- Batch status: `'.$r['batch_status'].'`'.($r['rehearsal'] ? ' (rehearsal)' : '');
        $out[] = '- Reconciliation: **'.($r['ok'] ? 'OK' : 'DISCREPANCIES').'**'.($r['discrepancies'] === [] ? '' : ' ('.implode(', ', $r['discrepancies']).')');
        $out[] = '';
        $out[] = '## Source rows versus staged rows';
        $out[] = '';
        $out[] = '| Source table | Source rows | Staged rows | mapped | needs_review | rejected | staged (unprocessed) |';
        $out[] = '|---|---:|---:|---:|---:|---:|---:|';
        foreach ($r['source'] as $table => $count) {
            $s = $r['states'][$table] ?? [];
            $out[] = sprintf(
                '| %s | %d | %d | %d | %d | %d | %d |',
                $table, $count, $r['staged'][$table] ?? 0,
                $s[LegacyStagingRow::STATE_MAPPED] ?? 0, $s[LegacyStagingRow::STATE_NEEDS_REVIEW] ?? 0,
                $s[LegacyStagingRow::STATE_REJECTED] ?? 0, $s[LegacyStagingRow::STATE_STAGED] ?? 0,
            );
        }
        $out[] = sprintf('| **total** | %d | %d | | | | |', array_sum($r['source']), array_sum($r['staged']));
        $out[] = '';
        $out[] = '## Reason codes for rows that are not mapped';
        $out[] = '';
        $out = array_merge($out, $this->table(['Reason code', 'Rows'], $r['reasons']));
        $out[] = '';
        $out[] = '## Identity maps (all start as `unpaired`)';
        $out[] = '';
        $out = array_merge($out, $this->table(['Status', 'Maps'], $r['maps']));
        $out[] = '';
        $out[] = '## Pair suggestions';
        $out[] = '';
        $out = array_merge($out, $this->table(['Status', 'Suggestions'], $r['suggestions']));
        $out[] = '';
        $out = array_merge($out, $this->table(['Signal kind', 'Suggestions carrying it'], $r['signal_kinds']));
        $out[] = '';
        $out[] = '## Coordinates parsed from map URLs (providers and arabic_providers staged rows)';
        $out[] = '';
        $out = array_merge($out, $this->table(['Result', 'Rows'], $r['coordinates']));
        $out[] = '';

        return implode("\n", $out);
    }

    /**
     * @param  list<string>  $headers
     * @param  array<string, int>  $rows
     * @return list<string>
     */
    private function table(array $headers, array $rows): array
    {
        $out = ['| '.implode(' | ', $headers).' |', '|---|---:|'];
        if ($rows === []) {
            $out[] = '| (none) | 0 |';
        }
        foreach ($rows as $key => $count) {
            $out[] = "| {$key} | {$count} |";
        }

        return $out;
    }

    /** @return array<string, int> */
    private function coordinateStats(LegacyMigrationBatch $batch): array
    {
        $stats = [
            RowNormalizer::COORD_PARSED => 0,
            RowNormalizer::COORD_OUT_OF_RANGE => 0,
            RowNormalizer::COORD_NONE => 0,
        ];

        LegacyStagingRow::query()->where('migration_batch_id', $batch->id)
            ->whereIn('source_table', ['providers', 'arabic_providers'])
            ->chunkById(500, function ($rows) use (&$stats) {
                foreach ($rows as $row) {
                    $status = $this->normalizer->provider((array) $row->payload)['coordinate_status'];
                    $stats[$status]++;
                }
            });

        return $stats;
    }
}
